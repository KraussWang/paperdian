const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const release = path.join(root, "release");
const marker = path.join(release, ".paperdian-generated");
const legacyMarker = path.join(release, ".paper-reading-generated");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "manifest.json"), "utf8"));
const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
if (manifest.version !== pkg.version) throw new Error("package.json and manifest.json versions differ.");
if (!fs.existsSync(path.join(root, "main.js"))) throw new Error("main.js is missing; run npm run build first.");
if (fs.existsSync(release)) {
  if (!fs.existsSync(marker) && !fs.existsSync(legacyMarker)) throw new Error("Existing release directory was not generated by this script.");
  fs.rmSync(release, { recursive: true });
}
fs.mkdirSync(path.join(release, "paperdian"), { recursive: true });
fs.mkdirSync(path.join(release, "skills"), { recursive: true });
for (const file of ["main.js", "manifest.json", "styles.css"]) {
  fs.copyFileSync(path.join(root, file), path.join(release, "paperdian", file));
}
for (const skill of ["material-paper-deep-reading", "material-paper-wechat-editor"]) {
  fs.cpSync(path.join(root, "src", "skills", "builtin", skill), path.join(release, "skills", skill), { recursive: true });
}
for (const file of ["LICENSE", "THIRD_PARTY_NOTICES.md"]) {
  fs.copyFileSync(path.join(root, file), path.join(release, file));
}
fs.copyFileSync(path.join(root, "docs", "INSTALL.md"), path.join(release, "INSTALL.md"));
fs.writeFileSync(marker, `Generated from manifest version ${manifest.version}\n`);
process.stdout.write(`Release staging: ${release}\n`);
